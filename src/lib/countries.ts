export function getCountryShortCode(country?: string | null): string | null {
  const raw = String(country || '').trim();
  if (!raw) return null;
  const q = raw.toLowerCase();

  const match = COUNTRIES.find((c) => {
    if (c.name.toLowerCase() === q) return true;
    if (c.code.toLowerCase() === q) return true;
    if (c.shortCode.toLowerCase() === q) return true;
    if (c.aliases) {
      const aliasTokens = c.aliases.toLowerCase().split(/\s+/);
      if (aliasTokens.includes(q)) return true;
    }
    return false;
  });

  if (match) return match.shortCode;
  return raw.replace(/[^a-zA-Z]/g, '').slice(0, 3).toUpperCase() || null;
}
